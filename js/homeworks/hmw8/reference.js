/**
 * High-precision Φ(z) for z on the grid (multiples of 0.01 with
 * |z| ≤ 10, multiples of 0.5 with 10 < |z| ≤ 37), else null.
 */
export function referenceCdf(z) {
  const x = Math.abs(z);
  let lower = null;

  const i = Math.round(x * 100);
  if (i <= 1000 && Math.abs(x * 100 - i) < 1e-9) lower = FINE[i];

  const k = Math.round((x - 10.5) * 2);
  if (lower === null && k >= 0 && k < TAIL.length && Math.abs((x - 10.5) * 2 - k) < 1e-9) {
    lower = TAIL[k];
  }

  if (lower === null) return null;
  return z <= 0 ? lower : 1 - lower;
}

/** Grid of z ≤ 0 used for the accuracy chart: 0, −0.01, …, −10. */
export const FINE_GRID = Array.from({ length: FINE.length }, (_, i) => -i / 100);
export const TAIL_GRID = Array.from({ length: TAIL.length }, (_, k) => -(10.5 + k / 2));
